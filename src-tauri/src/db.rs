    /// Column order must match `TASK_SELECT` exactly:
    /// id, title, notes, priority, status, due_at, tags, alarm_id, alarm_label,
    /// alarm_fire_at, created_at, updated_at, subtask_total, subtask_done,
    /// recurrence, recur_days, parent_id, completed_at, archived
    fn row_to_task(r: &rusqlite::Row) -> rusqlite::Result<Task> {
        let tags_raw: String = r.get(6)?;
        let recur_raw: String = r.get(15)?;
        Ok(Task {
            id: r.get(0)?,
            title: r.get(1)?,
            notes: r.get(2)?,
            priority: r.get(3)?,
            status: r.get(4)?,
            due_at: r.get(5)?,
            tags: serde_json::from_str(&tags_raw).unwrap_or_default(),
            alarm_id: r.get(7)?,
            alarm_label: r.get(8)?,
            alarm_fire_at: r.get(9)?,
            created_at: r.get(10)?,
            updated_at: r.get(11)?,
            subtask_total: r.get(12)?,
            subtask_done: r.get(13)?,
            recurrence: r.get(14)?,
            recur_days: serde_json::from_str(&recur_raw).unwrap_or_default(),
            parent_id: r.get(16)?,
            completed_at: r.get(17)?,
            archived: r.get::<_, i64>(18)? == 1,
        })
    }

    const TASK_SELECT: &'static str = r#"
        SELECT t.id, t.title, t.notes, t.priority, t.status, t.due_at, t.tags,
               a.id, a.label, a.fire_at, t.created_at, t.updated_at,
               (SELECT COUNT(*) FROM subtasks s WHERE s.task_id = t.id) AS total,
               (SELECT COUNT(*) FROM subtasks s WHERE s.task_id = t.id AND s.done = 1) AS done,
               t.recurrence, t.recur_days, t.parent_id, t.completed_at, t.archived
        FROM tasks t
        LEFT JOIN alarms a ON a.task_id = t.id AND a.state IN ('armed','paused')
    "#;

    /// Live tasks. Archived recurrence snapshots are excluded unless `filter` names
    /// them explicitly, so the list never shows the same task twice.
    pub fn list_tasks(&self, filter: &str, query: &str) -> Result<Vec<Task>, String> {
        let today_start = day_start(now_epoch());
        let today_end = today_start + 86_400;
        let mut sql = String::from(Self::TASK_SELECT);
        let mut where_parts: Vec<String> = vec![match filter {
            "occurrences" => "t.archived = 1".to_string(),
            _ => "t.archived = 0".to_string(),
        }];
        let mut args: Vec<Box<dyn rusqlite::ToSql>> = Vec::new();

        match filter {
            "today" => where_parts.push(format!("(t.due_at >= {today_start} AND t.due_at < {today_end})")),
            "overdue" => where_parts.push(format!("(t.due_at < {today_start} AND t.status != 'done')")),
            "high" => where_parts.push("(t.priority IN ('p1','p2') AND t.status != 'done')".to_string()),
            "completed" => where_parts.push("(t.status = 'done')".to_string()),
            "open" => where_parts.push("(t.status != 'done')".to_string()),
            "recurring" => where_parts.push("(t.recurrence != 'none')".to_string()),
            _ => {}
        }
        if !query.is_empty() {
            // One bound value, referenced three times by placeholder.
            let ph = args.len() + 1;
            where_parts.push(format!("(t.title LIKE ?{ph} OR t.notes LIKE ?{ph} OR t.tags LIKE ?{ph})"));
            args.push(Box::new(format!("%{query}%")));
        }
        sql.push_str(" WHERE ");
        sql.push_str(&where_parts.join(" AND "));
        sql.push_str(" ORDER BY (t.status='done'), CASE t.priority WHEN 'p1' THEN 1 WHEN 'p2' THEN 2 WHEN 'p3' THEN 3 ELSE 4 END, COALESCE(t.due_at, 9999999999)");

        let c = self.lock()?;
        let mut stmt = c.prepare(&sql).map_err(|e| e.to_string())?;
        let refs: Vec<&dyn rusqlite::ToSql> = args.iter().map(|a| a.as_ref()).collect();
        let rows = stmt
            .query_map(refs.as_slice(), Self::row_to_task)
            .map_err(|e| e.to_string())?;
        let mut out = Vec::new();
        for r in rows {
            out.push(r.map_err(|e| e.to_string())?);
        }
        Ok(out)
    }

    pub fn save_task(&self, input: &TaskInput) -> Result<Task, String> {
        let now = now_epoch();
        let tags = serde_json::to_string(&input.tags).unwrap_or_else(|_| "[]".into());
        let prio = norm_priority(&input.priority);
        let status = norm_status(&input.status);
        let recurrence = norm_recurrence(&input.recurrence);
        let recur_days = serde_json::to_string(&input.recur_days).unwrap_or_else(|_| "[]".into());
        let title = input.title.trim();
        if title.is_empty() {
            return Err("task title cannot be empty".into());
        }
        if recurrence != "none" && input.due_at.is_none() {
            return Err("a recurring task needs a due date".into());
        }
        let id = match input.id {
            Some(id) => {
                let c = self.lock()?;
                let prev: Option<(String, Option<i64>)> = c
                    .query_row(
                        "SELECT status, completed_at FROM tasks WHERE id=?1",
                        params![id],
                        |r| Ok((r.get(0)?, r.get(1)?)),
                    )
                    .optional()
                    .map_err(|e| e.to_string())?;
                let completed_at = match (status.as_str(), prev) {
                    ("done", Some((_, Some(existing)))) => Some(existing),
                    ("done", _) => Some(now),
                    _ => None,
                };
                c.execute(
                    "UPDATE tasks SET title=?1, notes=?2, priority=?3, status=?4, due_at=?5, tags=?6,
                              recurrence=?7, recur_days=?8, completed_at=?9, updated_at=?10 WHERE id=?11",
                    params![title, input.notes, prio, status, input.due_at, tags, recurrence, recur_days, completed_at, now, id],
                )
                .map_err(|e| e.to_string())?;
                id
            }
            None => {
                let c = self.lock()?;
                let completed_at = if status == "done" { Some(now) } else { None };
                c.execute(
                    "INSERT INTO tasks(title,notes,priority,status,due_at,tags,created_at,updated_at,
                                       recurrence,recur_days,parent_id,completed_at,archived)
                     VALUES(?1,?2,?3,?4,?5,?6,?7,?7,?8,?9,?10,?11,0)",
                    params![title, input.notes, prio, status, input.due_at, tags, now,
                            recurrence, recur_days, input.parent_id, completed_at],
                )
                .map_err(|e| e.to_string())?;
                c.last_insert_rowid()
            }
        };
        drop(self.lock()?);
        let task = self.task_by_id(id)?;
        self.log_activity(
            Some(id),
            if input.id.is_some() { "updated" } else { "created" },
            &format!("{} · {} · due {}", title, prio, input.due_at.map(|d| d.to_string()).unwrap_or_else(|| "-".into())),
        );
        Ok(task)
    }

    pub fn task_by_id(&self, id: i64) -> Result<Task, String> {
        let c = self.lock()?;
        c.query_row(
            &format!("{} WHERE t.id = ?1", Self::TASK_SELECT),
            params![id],
            Self::row_to_task,
        )
        .optional()
        .map_err(|e| e.to_string())?
        .ok_or_else(|| format!("task {id} not found"))
    }

    /// Sets status, stamping `completed_at`, and rolls a recurring task forward when
    /// the new status is `done`.
    pub fn set_task_status(&self, id: i64, status: &str) -> Result<Task, String> {
        let status = norm_status(status);
        let now = now_epoch();
        let completed_at = if status == "done" { Some(now) } else { None };
        {
            let c = self.lock()?;
            let title: String = c
                .query_row("SELECT title FROM tasks WHERE id=?1", params![id], |r| r.get(0))
                .unwrap_or_default();
            c.execute(
                "UPDATE tasks SET status=?1, completed_at=?2, updated_at=?3 WHERE id=?4",
                params![status, completed_at, now, id],
            )
            .map_err(|e| e.to_string())?;
            drop(c);
            self.log_activity(Some(id), "status", &format!("{status}: {title}"));
        }
        let task = self.task_by_id(id)?;
        if status == "done" && task.recurrence != "none" {
            if let Some(rolled) = self.roll_forward_recurring(&task)? {
                return Ok(rolled);
            }
        }
        Ok(task)
    }

