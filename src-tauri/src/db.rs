fn norm_priority(p: &str) -> String {
    match p {
        "p1" | "p2" | "p3" | "p4" => p.to_string(),
        _ => "p3".to_string(),
    }
}

fn norm_status(s: &str) -> String {
    match s {
        "todo" | "doing" | "done" => s.to_string(),
        _ => "todo".to_string(),
    }
}

fn norm_recurrence(r: &str) -> String {
    match r {
        "daily" | "weekdays" | "weekly" => r.to_string(),
        _ => "none".to_string(),
    }
}

/// Midnight (local) of the day containing `epoch`.
pub fn day_start(epoch: i64) -> i64 {
    let d = Local.timestamp_opt(epoch, 0).single().unwrap_or_else(Local::now);
    d.date_naive().and_hms_opt(0, 0, 0).and_then(|n| Local.from_local_datetime(&n).single()).map(|x| x.timestamp()).unwrap_or(epoch)
}

fn month_bounds(year: i32, month: i32) -> Result<(i64, i64), String> {
    let start = Local
        .with_ymd_and_hms(year, month as u32, 1, 0, 0, 0)
        .single()
        .ok_or_else(|| "invalid month".to_string())?;
    let (ny, nm) = if month == 12 { (year + 1, 1) } else { (year, month + 1) };
    let end = Local
        .with_ymd_and_hms(ny, nm as u32, 1, 0, 0, 0)
        .single()
        .ok_or_else(|| "invalid month".to_string())?;
    Ok((start.timestamp(), end.timestamp()))
}

struct SideSizes {
    wal: u64,
    shm: u64,
}
fn dir_sizes(db_path: &Path) -> SideSizes {
    let mut out = SideSizes { wal: 0, shm: 0 };
    for suffix in ["-wal", "-shm"] {
        let p = db_path.with_extension(format!("db{suffix}"));
        if let Ok(md) = std::fs::metadata(&p) {
            if suffix == "-wal" {
                out.wal = md.len();
            } else {
                out.shm = md.len();
            }
        }
    }
    out
}
