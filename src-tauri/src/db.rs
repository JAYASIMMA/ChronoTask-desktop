    pub fn save_alarm(&self, input: &AlarmInput) -> Result<Alarm, String> {
        let label = input.label.trim();
        if label.is_empty() {
            return Err("alarm label cannot be empty".into());
        }
        let repeat = match input.repeat.as_str() {
            "daily" | "weekdays" | "weekly" => input.repeat.clone(),
            _ => "none".to_string(),
        };
        let days = serde_json::to_string(&input.days).unwrap_or_else(|_| "[]".into());
        let snooze = input.snooze_min.clamp(1, 240);
        let sound = match input.sound.as_str() {
            "bell" | "pulse" | "silent" => input.sound.clone(),
            _ => "chime".to_string(),
        };
        let advance = input.advance_min.clamp(0, 1440);
        let max_snoozes = input.max_snoozes.clamp(0, 20);
        let escalate: i64 = if input.escalate { 1 } else { 0 };
        let id = match input.id {
            Some(id) => {
                let c = self.lock()?;
                c.execute(
                    "UPDATE alarms SET label=?1, fire_at=?2, repeat=?3, days=?4, snooze_min=?5, sound=?6,
                              task_id=?7, advance_min=?8, max_snoozes=?9, escalate=?10,
                              state='armed', last_fired_at=NULL, snooze_count=0, last_preflight_for=NULL WHERE id=?11",
                    params![label, input.fire_at, repeat, days, snooze, sound, input.task_id,
                            advance, max_snoozes, escalate, id],
                )
                .map_err(|e| e.to_string())?;
                id
            }
            None => {
                let c = self.lock()?;
                c.execute(
                    "INSERT INTO alarms(label,fire_at,repeat,days,snooze_min,sound,state,task_id,created_at,
                                        advance_min,max_snoozes,escalate)
                     VALUES(?1,?2,?3,?4,?5,?6,'armed',?7,?8,?9,?10,?11)",
                    params![label, input.fire_at, repeat, days, snooze, sound, input.task_id,
                            now_epoch(), advance, max_snoozes, escalate],
                )
                .map_err(|e| e.to_string())?;
                c.last_insert_rowid()
            }
        };
        drop(self.lock()?);
        let alarm = self.alarm_by_id(id)?;
        let _ = self.record_alarm_event(Some(id), &alarm.label, "armed", alarm.fire_at, &format!("repeat={}", alarm.repeat));
        Ok(alarm)
    }

    pub fn set_alarm_state(&self, id: i64, state: &str) -> Result<Alarm, String> {
        let state = match state {
            "armed" | "paused" | "dismissed" => state.to_string(),
            _ => return Err(format!("invalid alarm state: {state}")),
        };
        {
            let c = self.lock()?;
            c.execute(
                "UPDATE alarms SET state=?1, snooze_count=CASE WHEN ?1='armed' THEN 0 ELSE snooze_count END WHERE id=?2",
                params![state, id],
            )
            .map_err(|e| e.to_string())?;
        }
        let alarm = self.alarm_by_id(id)?;
        let event = match state.as_str() {
            "armed" => "resumed",
            "paused" => "paused",
            _ => "dismissed",
        };
        let _ = self.record_alarm_event(Some(id), &alarm.label, event, alarm.fire_at, "");
        Ok(alarm)
    }

