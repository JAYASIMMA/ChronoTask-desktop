    /// Re-arm an alarm `minutes` from now, honouring its snooze budget. Once
    /// `max_snoozes` is exhausted the alarm dismisses itself instead of re-arming, so
    /// a nagging alarm cannot be snoozed into oblivion.
    pub fn snooze_alarm(&self, id: i64, minutes: i64) -> Result<Alarm, String> {
        let m = minutes.clamp(1, 240);
        let current = self.alarm_by_id(id)?;
        if current.max_snoozes > 0 && current.snooze_count >= current.max_snoozes {
            let c = self.lock()?;
            c.execute("UPDATE alarms SET state='dismissed' WHERE id=?1", params![id])
                .map_err(|e| e.to_string())?;
            drop(c);
            let _ = self.record_alarm_event(
                Some(id),
                &current.label,
                "disabled",
                current.fire_at,
                &format!("snooze limit reached ({})", current.max_snoozes),
            );
            return self.alarm_by_id(id);
        }
        {
            let c = self.lock()?;
            c.execute(
                "UPDATE alarms SET fire_at=?1, last_fired_at=NULL, state='armed',
                                     snooze_count=snooze_count+1, last_preflight_for=NULL WHERE id=?2",
                params![now_epoch() + m * 60, id],
            )
            .map_err(|e| e.to_string())?;
        }
        let alarm = self.alarm_by_id(id)?;
        let _ = self.record_alarm_event(
            Some(id),
            &alarm.label,
            "snoozed",
            alarm.fire_at,
            &format!("+{m}m ({} of {})", alarm.snooze_count, if alarm.max_snoozes == 0 { "∞".to_string() } else { alarm.max_snoozes.to_string() }),
        );
        Ok(alarm)
    }

